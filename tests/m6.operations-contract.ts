import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { setTimeout as delay } from 'node:timers/promises';

export async function verifyOperatingApi(h: { base: string; tenantId: string; foreignTenant: string; token: string; request(tenant: string, path: string, body?: unknown, headers?: Record<string, string>): Promise<{ status: number; data: any }>; waitStatus(tenant: string, id: string, status: string): Promise<any>; sourceRunId: string }) {
  const { GatewayWorkflowClient, PlatformClient } = await import('../packages/sdk/dist/index.js');
  const client = new PlatformClient(new GatewayWorkflowClient({ baseUrl: h.base, headers: async () => ({ Authorization: `Bearer ${h.token}` }) }));
  const first = await client.summary();
  await h.request(h.tenantId, '/api/catalog');
  let last = first;
  for (let i = 0; i < 30 && last.http.requests <= first.http.requests; i++) { await delay(100); last = await client.summary(); }
  assert.ok(last.http.requests > first.http.requests);
  assert.ok(last.http.meanLatencyMs !== null && last.http.meanLatencyMs >= 0);
  assert.equal((await h.request(h.tenantId, '/api/evals/agents')).data.synthetic, false);
  assert.equal((await h.request(h.tenantId, '/api/evals/agents/unknown/report')).status, 410);
  const schedule = await h.request(h.tenantId, '/api/scheduler/jobs', { name: 'Bound event fixture', skillId: 'eng-007', personaId: 'engineering', scheduleType: 'event', eventTrigger: 'm6.fixture', simulate: true, inputBindings: { code_or_module: 'event.code' }, inputs: {} });
  assert.equal(schedule.status, 201);
  const event = await h.request(h.tenantId, '/api/scheduler/events', { trigger: 'm6.fixture', deliveryId: 'fixture-event', data: { code: 'event supplied fixture text' } });
  assert.equal(event.status, 200);
  const result = await h.waitStatus(h.tenantId, event.data.runs[0], 'simulated');
  assert.equal(result.inputs.code_or_module, 'event supplied fixture text');
  assert.equal((await h.request(h.tenantId, '/api/scheduler/events', { trigger: 'm6.fixture', deliveryId: 'fixture-event', data: { code: 'changed payload' } })).status, 409);
  const channel = await h.request(h.tenantId, '/api/notifications/channels', { name: 'Fixture Slack', channel: 'slack', enabled: true, config: { connectionId: 'slack', destination: 'C123' } });
  assert.equal(channel.status, 201);
  const notification = await client.notify(channel.data.channel.id, h.sourceRunId, 'fixture-notification', true);
  await h.waitStatus(h.tenantId, notification.execution.id, 'simulated');
  assert.equal((await client.notify(channel.data.channel.id, h.sourceRunId, 'fixture-notification', true)).execution.id, notification.execution.id);
  const deliveries = await h.request(h.tenantId, '/api/operations/notifications');
  assert.equal(deliveries.data.notifications.find((row: any) => row.executionId === notification.execution.id)?.status, 'simulated');
  await assert.rejects(client.notify(channel.data.channel.id, h.sourceRunId, 'forbidden-live-notification', false));
  const page = await client.events();
  assert.ok(page.events.every(event => !event.data.tenantId || event.data.tenantId === h.tenantId));
  const next = await client.events(page.cursor);
  assert.ok(next.events.every(event => !page.events.some(previous => previous.id === event.id)));
  const prompt = await h.request(h.tenantId, '/api/prompts', { name: 'fixture-reviewed-prompt', persona: 'engineering', agentId: 'code-reviewer', content: 'Use supplied fixture evidence; do not invent facts.', origin: 'local:fixture', license: 'MIT', visibility: 'private' });
  assert.equal(prompt.status, 201);
  const prompts = await h.request(h.tenantId, '/api/prompts');
  assert.equal(prompts.data.authority, 'canonical-registry');
  assert.ok(!prompts.data.prompts.some((row: any) => row.id === prompt.data.packageId));
  const preview = await client.preview(prompt.data.packageId, prompt.data.hash, { user_input: 'Fixture prompt input' }, true, 'prompt-preview-fixture');
  await h.waitStatus(h.tenantId, preview.execution.id, 'simulated');
  await assert.rejects(client.execute(prompt.data.packageId, { user_input: 'Fixture' }, true, 'unapproved-execution'));
  const contracts = await client.connectorContracts();
  assert.equal(contracts.activationEnabled, false);
  assert.equal(contracts.contracts.flatMap(contract => contract.actions).length, 6);
  const connector = await client.stage({ name: 'http.fixture.connector', kind: 'connector', definition: { schemaVersion: 1, id: 'github', actions: ['github:read:pull_request'] }, origin: 'local:fixture', license: 'MIT', visibility: 'private' });
  const conformance = await client.connectorConformance(connector.packageId, connector.hash);
  assert.equal(conformance.activationEligible, false);
  assert.equal(conformance.adapterCurrent, true);
  assert.ok(conformance.blockers.includes('vendor_sandbox_certification_pending'));
  assert.equal((await h.request(h.foreignTenant, `/api/registry/packages/${connector.packageId}/conformance?hash=${connector.hash}`)).status, 403);
  assert.equal((await h.request(h.tenantId, `/api/registry/packages/${connector.packageId}/conformance`, { passed: true, transport: 'native_transport' })).status, 404);
  await assert.rejects(client.activate(connector.packageId, connector.hash, connector.revision));
  const cli = spawn(process.execPath, ['packages/cli/dist/index.js', 'ops'], { env: { PATH: process.env.PATH, GATEWAY_URL: h.base, EAOS_TOKEN: h.token }, stdio: ['ignore','pipe','pipe'] });
  let output = '', error = '';
  cli.stdout.on('data', chunk => { output += chunk.toString(); }); cli.stderr.on('data', chunk => { error += chunk.toString(); });
  const [code] = await once(cli, 'exit');
  assert.equal(code, 0, error);
  assert.ok(JSON.parse(output).http.requests >= last.http.requests);
  assert.equal(output.includes(h.token), false);
  const denied = spawn(process.execPath, ['packages/cli/dist/index.js', 'ops'], { env: { PATH: process.env.PATH, GATEWAY_URL: h.base }, stdio: ['ignore','pipe','pipe'] });
  denied.stdout.resume(); denied.stderr.resume();
  assert.notEqual((await once(denied, 'exit'))[0], 0);
  console.log('PASS measured HTTP/SDK/CLI operations, ordered event replay, event input bindings and explicit notification provenance');
}
